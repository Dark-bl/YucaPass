import assert from 'node:assert/strict';
import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
const root = process.cwd();
const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const cap = JSON.parse(await readFile(path.join(root, 'capacitor.config.json'), 'utf8'));
const release = JSON.parse(await readFile(path.join(root, 'app-release.config.json'), 'utf8'));
const workflow = await readFile(path.join(root, '.github/workflows/android-release.yml'), 'utf8');
const prepare = await readFile(path.join(root, 'scripts/prepare-android.mjs'), 'utf8');
const signing = await readFile(path.join(root, 'scripts/configure-release-signing.mjs'), 'utf8');
assert.equal(pkg.version, '5.0.0');
assert.equal(cap.appId, 'mx.yucapass.turismo');
assert.equal(cap.appName, 'YucaPass');
assert.equal(cap.plugins?.SplashScreen?.backgroundColor, '#062D46');
assert.equal(release.targetSdkVersion, 36);
assert.equal(release.versionCode, 50000);
assert.equal(pkg.dependencies['@capacitor/splash-screen'], '8.0.2');
assert.match(workflow, /platforms;android-36/);
assert.match(workflow, /assembleDebug/);
assert.match(workflow, /bundleRelease/);
assert.match(workflow, /ANDROID_KEYSTORE_BASE64/);
assert.match(prepare, /ic_launcher_foreground/);
assert.match(prepare, /targetSdkVersion/);
assert.match(signing, /ANDROID_KEYSTORE_PASSWORD/);
assert.doesNotMatch(workflow, /-----BEGIN PRIVATE KEY-----/);
const icon = path.join(root, 'assets/android/launcher/ic_launcher_foreground.png');
await stat(icon);
const splash = path.join(root, 'assets/android/splash/splash.png');
await stat(splash);
const playReadiness = await readFile(path.join(root, 'PLAY_STORE_READINESS.md'), 'utf8');
assert.match(playReadiness, /eliminación de cuenta/i);
assert.match(playReadiness, /pendiente/i);
console.log('OK: versionado 5.0, identidad Android, API 36, splash, icono y flujo de firma separados de secretos.');
